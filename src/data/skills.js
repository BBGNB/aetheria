export const SKILL_BY_ID = Object.fromEntries(SKILLS.map(s => [s.id, s]));

// Given a list of currently-granted skill ids (from class tree + gems + combos),
// resolve the final visible list. Active tiers (attack/magic/heal) all stay
// visible so the player can still cast the cheaper lower-tier versions when
// MP is short. Passive tiers are deduplicated so their stat bonuses don't
// stack with their own lower tiers (stoneSkin replaces ironSkin).
export function resolveTieredSkills(grantedIds) {
  const set = new Set(grantedIds);
  for (const id of grantedIds) {
    const s = SKILL_BY_ID[id];
    if (!s?.baseId) continue;
    const base = SKILL_BY_ID[s.baseId];
    if (base?.kind === 'passive') set.delete(s.baseId);
  }
  return [...set];
}
